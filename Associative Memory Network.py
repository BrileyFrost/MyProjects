class ModernHopfield:
    def __init__(self,n_memories):
        self.N = n_memories
        self.W = np.random.randn(n_memories,n_memories)
    def Initialize_Weights(self,patterns):
        for pattern in patterns:
            self.W += np.outer(pattern,pattern)
        np.fill_diagonal(self.W,0)
    def Energy(self,state,log=False,pattern=0):
        if log == False:
            E = 0
            for i in range(self.N):
                E -= np.dot(state,self.W)
        else:
            E=0
            for i in range(self.N):
                E += np.exp(np.dot(state,self.W))
            E = 0.5 * ((pattern*pattern) * -np.log(E))
        return E
    def WeightUpdate(self,pattern,prediction,lr=0.5):
        self.W -= Softmax(np.dot(lr*prediction.T,pattern))
    def Forward(self,pattern):
        h = np.dot(pattern,self.W)
        pattern = np.tanh(h)
        return pattern
    
