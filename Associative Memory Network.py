class ContinousBoltzmannMachine:
    def __init__(self,H,In,W=0):
        self.hidden = H
        self.visible = In
        if W!=0:
            self.weight = W[0]
            self.a = W[1]
            self.b = W[2]
        else:
            self.weight = np.random.randn(H,In)* np.sqrt(1. / H)
            self.a = np.random.randn(1, H)* np.sqrt(1. / H)
            self.b = np.random.randn(1, In)* np.sqrt(1. / In)
        self.sigma = np.ones(In)
    def sample_h(self,X):
        wx = np.matmul(X/self.sigma, self.weight.T)
        activation = wx + self.a
        p_h_given_v = sigmoid(activation)
        return (p_h_given_v > np.random.rand(*p_h_given_v.shape)).astype(float)
    def sample_v(self, y):
        wy = np.matmul(y, self.weight) * self.sigma
        activation = wy + self.b
        return activation + np.random.randn(*activation.shape)*self.sigma
    def train(self, v0, vk, ph0, phk,lr=0.001):
        self.weight += np.array((np.matmul(v0.T, ph0) - np.matmul(vk.T, phk)).T)*lr
        self.b += np.sum((v0 - vk), axis=0)*lr/self.sigma**2
        self.a += np.sum((ph0 - phk), axis=0)*lr


